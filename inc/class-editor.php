<?php
/**
 * Group block editor integration.
 *
 * @package ContentGates
 */

declare( strict_types=1 );

namespace ContentGates;

/**
 * Loads the Segment inspector control.
 */
final class Editor {

	/**
	 * Register WordPress hooks.
	 */
	public static function register_hooks(): void {
		add_action( 'enqueue_block_editor_assets', array( self::class, 'enqueue_assets' ) );
	}

	/**
	 * Enqueue the built editor script and segment records.
	 */
	public static function enqueue_assets(): void {
		$asset_file = CONTENT_GATES_PATH . 'build/index.asset.php';
		$script     = CONTENT_GATES_PATH . 'build/index.js';

		if ( ! is_readable( $asset_file ) || ! is_readable( $script ) ) {
			return;
		}

		/**
		 * Editor asset metadata generated by wp-scripts.
		 *
		 * @var array{dependencies:list<non-empty-string>,version:string} $asset
		 */
		$asset        = require $asset_file;
		$dependencies = array_merge(
			$asset['dependencies'],
			array( 'wp-block-editor', 'wp-components', 'wp-compose', 'wp-element', 'wp-hooks', 'wp-i18n' )
		);
		wp_enqueue_script(
			'content-gates-editor',
			plugins_url( 'build/index.js', dirname( __DIR__ ) . '/content-gates.php' ),
			array_values( array_unique( $dependencies ) ),
			$asset['version'],
			true
		);

		$segments = array_map(
			static function ( \WP_Post $segment ): array {
				return array(
					'id'     => (int) $segment->ID,
					'name'   => $segment->post_title,
					'active' => Segment_Repository::STATUS_ACTIVE === $segment->post_status,
				);
			},
			Segment_Repository::get_all()
		);

		wp_localize_script(
			'content-gates-editor',
			'contentGatesEditorSettings',
			array( 'segments' => $segments )
		);
	}
}
